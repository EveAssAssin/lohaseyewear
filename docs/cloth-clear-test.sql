-- =============================================================
-- 【第一步】先看清楚要刪的是什麼
-- -------------------------------------------------------------
-- 逐筆確認 erpid 是不是自己人(28095839),或 member_name 認得出來。
-- 有任何一筆不認得,就【停下來】,不要往下跑。
-- =============================================================

select
  id,
  created_at at time zone 'Asia/Taipei' as 建立時間,
  status                                as 狀態,
  coalesce(erpid, '(無客編)')            as 客編,
  coalesce(mid,   '(無 mid)')            as mid,
  coalesce(member_name, '(未提供)')      as 姓名,
  source                                as 來源,
  coalesce(design_name, '(未命名)')      as 圖名,
  coalesce(store_name, '(未指定門市)')   as 取貨門市
from public.cloth_designs
order by created_at desc;


-- =============================================================
-- 【第二步】把檔案路徑抄下來 —— 刪了資料列就找不到它們了
-- -------------------------------------------------------------
-- ⚠ 這一步很容易被跳過,而跳過的代價是【永久的垃圾】:
--   圖檔在 Storage 裡,不會跟著資料列一起消失。
--   資料列刪掉之後,沒有任何地方記得那些檔案的存在 ——
--   它們會永遠佔著空間,而且沒有人知道那是什麼。
--
-- 把這一段的輸出複製到記事本,第三步刪完之後,到
--   Storage → gallery-uploads → cloth/
-- 手動把這些檔案刪掉。
-- =============================================================

/* ⚠⚠ 兩個欄位【歸屬不同】,不可以一起刪。
   -------------------------------------------------------------
   從刻圖市集選圖時,眼鏡布【沿用市集那件作品的原始 SVG】,
   不會另外上傳一份(見 js/cloth.js 的 svgStep:
   `State.picked.svgUrl ? 直接用 : 才上傳`)。

   所以那種資料列的 svg_url 長這樣:
     engraving-uploads/designs/28394044/…svg   ← 市集作品的,共用
   而 preview_url 才是這張眼鏡布自己產的:
     cloth/1787841959835-mm3190-preview.jpg

   刪掉前者 = 把市集裡那張刻圖弄壞,所有人都看不到。

   ✅ 判斷方法:【路徑裡有 cloth/ 的才是眼鏡布自己的】。
      下面那兩欄會標出來,只刪標著「✅ 可刪」的。 */

select
  case when svg_url like '%/cloth/%'
       then '✅ 可刪 · ' || regexp_replace(svg_url, '^.*/cloth/', 'cloth/')
       else '⛔ 不要動(市集共用) · ' || svg_url
  end as svg檔,
  case when preview_url like '%/cloth/%'
       then '✅ 可刪 · ' || regexp_replace(preview_url, '^.*/cloth/', 'cloth/')
       else '⛔ 不要動 · ' || preview_url
  end as 合成圖
from public.cloth_designs
order by created_at desc;


-- =============================================================
-- 【第三步】刪。確認過第一步之後才跑這一段。
-- -------------------------------------------------------------
-- 用 returning 把刪掉的東西印出來,當作一份「我確實刪了這些」的
-- 憑據 —— 事後若發現少了什麼,至少查得到是不是這一刀砍的。
-- =============================================================

delete from public.cloth_designs
returning id, created_at, status, erpid, design_name;


-- =============================================================
-- 【第四步】確認乾淨了
-- =============================================================

select count(*) as 剩下幾筆 from public.cloth_designs;


/* =============================================================
   ⚠ 如果只想刪自己人的、保留其他人的
   -------------------------------------------------------------
   把第三步換成這一段(erpid 換成要保留/刪除的那一個):

     delete from public.cloth_designs
     where erpid = '28095839'
     returning id, created_at, status, design_name;

   或只刪某一天之前的:

     delete from public.cloth_designs
     where created_at < '2026-08-28'::timestamptz
     returning id, created_at, status, design_name;
   ============================================================= */


