-- 2026-08-27。⚠ 這是【正式站】的資料,刪掉救不回來。
--
-- 分兩步:先看,再刪。不要跳過第一步 ——
-- 8/27 的紀錄裡有 9 筆(1 筆 done、8 筆 new),那些都是這個功能
-- 開發期間存的;但「應該全部是自己人」與「確實全部是自己人」
-- 是兩回事,而且只有一次機會分辨。
